import type { AccountSession } from "./account";

/**
 * O botão do olho abre uma segunda instância do Artisan em modo
 * de Espectador — a dedicated, read-only viewer that always follows the
 * Mestre's camera, replacing the old "force every connected Player to
 * follow" behaviour of the camera-share toggle.
 */

export const SPECTATOR_QUERY_PARAM = "spectator";

/** True when the given `location.search` string marks this window as the
 * read-only Espectador viewer (routes/Game.tsx reads this once per mount). */
export function isSpectatorSearch(search: string): boolean {
  return new URLSearchParams(search).get(SPECTATOR_QUERY_PARAM) === "1";
}

export function buildSpectatorPath(gameId: string): string {
  return `/game/${gameId}?${SPECTATOR_QUERY_PARAM}=1`;
}

/**
 * Opens the Espectador viewer for the given Mesa.
 *
 * Wails v2 (this repo's desktop shell) has no built-in multi-window
 * support, so "abrir uma segunda instância" is literally that: a second OS
 * PROCESS of the same binary, given its OWN WebView2 profile (see
 * desktop/main.go) and told which Mesa to open plus the calling account's
 * session (so it can self-login instead of showing a fresh login form,
 * since its separate profile has no session of its own) via CLI flags its
 * own `main()` reads at startup. Reached through the Wails-injected
 * `window.go.main.App...` runtime global rather than a static import of
 * the generated `wailsjs` bindings: those live under
 * `desktop/frontend/wailsjs`, generated by `wails build` from the ALREADY
 * -BUILT frontend (see the skill's build/deploy notes) — a static import
 * from `src/` would resolve a path that doesn't exist yet on a fresh
 * checkout, and doesn't exist at all in the standalone web build.
 *
 * Falls back to a plain new browser tab (same origin, so it shares the
 * same account session/localStorage/IndexedDB) for the web build/preview,
 * or if the desktop binding call itself fails for any reason.
 */
export function openSpectatorWindow(
  gameId: string,
  session: AccountSession | undefined
): void {
  const openFn = (window as any)?.go?.main?.App?.OpenSpectatorWindow;
  if (typeof openFn === "function") {
    Promise.resolve(openFn(gameId, session ? JSON.stringify(session) : ""))
      .catch(() => openSpectatorTab(gameId));
    return;
  }
  openSpectatorTab(gameId);
}

function openSpectatorTab(gameId: string): void {
  window.open(buildSpectatorPath(gameId), "_blank", "noopener");
}

/**
 * Resolves the Mesa id THIS desktop process was launched to spectate (see
 * `openSpectatorWindow` above), or undefined for a normal launch — and
 * always undefined in the web build, where `window.go` doesn't exist at
 * all. Called once at app startup (routes/Home.tsx) to auto-navigate
 * straight into a game in spectator mode instead of showing Home.
 */
export async function getLaunchSpectatorGameId(): Promise<string | undefined> {
  const getFn = (window as any)?.go?.main?.App?.GetSpectatorGameID;
  if (typeof getFn !== "function") {
    return undefined;
  }
  try {
    const id = await getFn();
    return id || undefined;
  } catch {
    return undefined;
  }
}

/**
 * Resolves the AccountSession THIS desktop process was launched with (see
 * `openSpectatorWindow` above's `sessionJSON` argument), or undefined for
 * a normal launch. Consumed once by AccountContext's initial load so a
 * spectator window — whose separate WebView2 profile has no session of
 * its own — starts already logged in as the SAME account that opened it,
 * instead of showing a login form.
 */
export async function getLaunchSpectatorSession(): Promise<
  AccountSession | undefined
> {
  const getFn = (window as any)?.go?.main?.App?.GetSpectatorSession;
  if (typeof getFn !== "function") {
    return undefined;
  }
  try {
    const json = await getFn();
    if (!json) {
      return undefined;
    }
    return JSON.parse(json) as AccountSession;
  } catch {
    return undefined;
  }
}
